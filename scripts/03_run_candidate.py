#!/usr/bin/env python3
"""Run the smoke suite as the **candidate** (Milestone 4).

Thin wrapper over ``llmreg run-suite``. The candidate is generated by the
``scripted-regression`` adapter, which applies exactly one mechanical defect to
each non-control baseline response — the ground truth the detector is measured
against in Milestone 6. Offline, CPU-only, no model call, no network.

    python3 scripts/03_run_candidate.py [-- EXTRA llmreg run-suite ARGS]

Writes ``results/runs/smoke-candidate-scripted-regression/{run.jsonl,run_meta.json}``.
Any extra arguments are appended verbatim, so the defaults can be overridden:

    python3 scripts/03_run_candidate.py --dry-run
    python3 scripts/03_run_candidate.py --out /tmp/runs --run-id my-candidate

The prompt/tool versions and timestamp below are **synthetic labels** for the
deployment the candidate stands for — a prompt and tool revision one week after
the recorded baseline. They are inputs, not readings of the clock. The behavioral
differences come from the scripted injectors, not from these labels. ``model_id``
is deliberately left to the executor, which names the adapter that produced the
outputs rather than a model that was never called.

Pair it with ``scripts/02_run_baseline.py``; Milestone 6's ``llmreg compare``
consumes the two run directories.
"""

from __future__ import annotations

import sys
from pathlib import Path

_SRC = Path(__file__).resolve().parent.parent / "src"
if _SRC.is_dir() and str(_SRC) not in sys.path:
    sys.path.insert(0, str(_SRC))

from llm_regression_observability import cli  # noqa: E402

SUITE = "evals/suites/smoke.yaml"
OUT = "results/runs"

# Synthetic labels for the candidate deployment (recorded inputs, never ambient).
PROMPT_VERSION = "p-2026-06-08"
TOOL_VERSION = "t-2026-06-08"
TIMESTAMP = "2026-06-08T12:00:00Z"


def main(argv: list[str]) -> int:
    args = [
        "run-suite",
        "--suite", SUITE,
        "--adapter", "scripted-regression",
        "--app-version", "candidate",
        "--out", OUT,
        "--prompt-version", PROMPT_VERSION,
        "--tool-version", TOOL_VERSION,
        "--timestamp", TIMESTAMP,
        *argv,
    ]
    return cli.main(args)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
