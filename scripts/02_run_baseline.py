#!/usr/bin/env python3
"""Run the smoke suite as the **baseline** (Milestone 4).

Thin wrapper over ``llmreg run-suite`` so the run is reproducible without an
editable install (it prepends ``src/`` to the path, like ``conftest.py``). The
baseline is generated by the ``recorded`` adapter, which replays the committed
synthetic fixtures — offline, CPU-only, no model call, no network.

    python3 scripts/02_run_baseline.py [-- EXTRA llmreg run-suite ARGS]

Writes ``results/runs/smoke-baseline-recorded/{run.jsonl,run_meta.json}``.
Any extra arguments are appended verbatim, so the defaults can be overridden:

    python3 scripts/02_run_baseline.py --dry-run
    python3 scripts/02_run_baseline.py --out /tmp/runs --run-id my-baseline
"""

from __future__ import annotations

import sys
from pathlib import Path

_SRC = Path(__file__).resolve().parent.parent / "src"
if _SRC.is_dir() and str(_SRC) not in sys.path:
    sys.path.insert(0, str(_SRC))

from llm_regression_observability import cli  # noqa: E402

SUITE = "evals/suites/smoke.yaml"
OUT = "results/runs"


def main(argv: list[str]) -> int:
    args = [
        "run-suite",
        "--suite", SUITE,
        "--adapter", "recorded",
        "--app-version", "baseline",
        "--out", OUT,
        *argv,
    ]
    return cli.main(args)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
